#!/usr/bin/env python3
"""Writes src/components/icons/zarzardIcons.h from the Phosphor SVGs in svg/ (MIT) and
tatakae.pbm (戦え rendered from Noto Serif CJK JP, OFL). Needs cairosvg and Pillow."""
import glob, io, os
import cairosvg
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "src", "components", "icons", "zarzardIcons.h")
WANT = [("cards", "fill", 32), ("fire", "fill", 24), ("book-open", "regular", 32),
        ("notebook", "regular", 40), ("folder-open", "regular", 40), ("clock-counter-clockwise", "regular", 40),
        ("arrows-left-right", "regular", 40), ("rss", "regular", 40), ("gear-six", "regular", 40),
        ("calendar-check", "fill", 40), ("calendar-check", "regular", 40), ("list-numbers", "regular", 40),
        ("chart-bar", "regular", 40), ("gear-six", "regular", 32),
        ("x-circle", "regular", 32), ("question", "regular", 32), ("check-circle", "regular", 32),
        ("lightning", "regular", 32), ("eye", "regular", 32), ("arrow-u-up-left", "regular", 32),
        ("bookmark-simple", "fill", 24)]

def raster(name, weight, size):
    svg = os.path.join(HERE, "svg", f"{name}-{weight}.svg")
    png = cairosvg.svg2png(url=svg, output_width=size * 4, output_height=size * 4)
    im = Image.open(io.BytesIO(png)).convert("RGBA")
    bg = Image.new("RGBA", im.size, (255, 255, 255, 255)); bg.alpha_composite(im)
    return bg.convert("L").resize((size, size), Image.LANCZOS).point(lambda v: 0 if v < 140 else 255).convert("1")

def pack(im):
    w, h = im.size; px = im.load(); rb = (w + 7) // 8; data = []
    for y in range(h):
        for bx in range(rb):
            b = 0
            for k in range(8):
                x = bx * 8 + k
                if x < w and px[x, y] == 0: b |= 0x80 >> k
            data.append(b)
    rows = [", ".join(f"0x{v:02X}" for v in data[i:i + 16]) for i in range(0, len(data), 16)]
    return ",\n    ".join(rows)

out = ["#pragma once", "// Phosphor Icons (MIT, (c) 2023 Phosphor Icons) rasterized for the Zarzard theme,",
       "// and the 戦え mark in Noto Serif CJK JP (OFL). Generated by scripts/zarzard_icons/gen_icons.py.",
       "// Row-major, MSB first, bit 1 = ink.", "#include <cstdint>", "", "namespace ZarzardIcons {", "",
       "struct Icon {", "  const uint8_t* bits;", "  uint8_t size;", "};", "", "struct Picture {",
       "  const uint8_t* bits;", "  uint16_t width;", "  uint16_t height;", "};", ""]
for n, w, s in WANT:
    ident = "".join(p.capitalize() for p in n.split("-")) + ("Fill" if w == "fill" else "") + str(s)
    out.append(f"inline constexpr uint8_t k{ident}Bits[] = {{\n    {pack(raster(n, w, s))}}};")
    out.append(f"inline constexpr Icon {ident}{{k{ident}Bits, {s}}};")
    out.append("")
mark = Image.open(os.path.join(HERE, "tatakae.pbm")).convert("1")
out.append(f"inline constexpr uint8_t kTatakaeBits[] = {{\n    {pack(mark)}}};")
out.append(f"inline constexpr Picture Tatakae{{kTatakaeBits, {mark.size[0]}, {mark.size[1]}}};")
out += ["", "}  // namespace ZarzardIcons", ""]
open(OUT, "w").write("\n".join(out))
print("icons:", len(WANT))
